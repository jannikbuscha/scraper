import { screen, waitFor, within } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';

import type { Proposal } from '../../api/acquisition-types';
import { exampleProposal, p2Meta, p2Vocabularies } from '../../test/acquisition-fixtures';
import { callsTo, jsonBody, mockApi } from '../../test/api-mock';
import { renderRoute } from '../../test/render';
import { EditAcceptModal } from './EditAcceptModal';

function renderForm(proposal: Proposal) {
  const fetchMock = mockApi((url) =>
    url.pathname === `/api/proposals/${proposal.id}/accept`
      ? { proposal: { ...proposal, state: 'accepted_modified' }, changed: true, result_id: 'prj_A', revision_ids: [1], batch_id: null }
      : url.pathname === '/api/lookup'
        ? { items: [] }
        : undefined,
  );
  const onAccepted = vi.fn();
  const Page = () => (
    <EditAcceptModal
      proposal={proposal}
      refs={{ prj_A: { id: 'prj_A', type: 'project', label: 'Example project A', deleted: false } }}
      meta={p2Meta}
      onClose={vi.fn()}
      onAccepted={onAccepted}
    />
  );
  const rendered = renderRoute(Page, { url: '/review', path: '/review', vocabularies: p2Vocabularies });
  const acceptBody = () => jsonBody(callsTo(fetchMock, `/api/proposals/${proposal.id}/accept`)[0]?.init);
  return { ...rendered, fetchMock, onAccepted, acceptBody };
}

const dialog = () => screen.findByRole('dialog');

describe('edit & accept sends only the changed values (docs/UI.md §8.2)', () => {
  it('update_field: the edited field, or no values when unchanged', async () => {
    const proposal = exampleProposal({ field: 'name_en', live_value: 'Example name', proposed_value: 'Example name (source)' });
    const { user, acceptBody, onAccepted } = renderForm(proposal);
    const form = within(await dialog());
    const input = form.getByRole('textbox', { name: /Name \(EN\)/ });
    expect(input).toHaveValue('Example name (source)');
    await user.clear(input);
    await user.type(input, 'Example name (edited)');
    await user.click(form.getByRole('button', { name: 'Accept' }));
    await waitFor(() => {
      expect(onAccepted).toHaveBeenCalled();
    });
    expect(acceptBody()).toEqual({ values: { name_en: 'Example name (edited)' }, note: null });
  });

  it('update_field unchanged: accepted as proposed', async () => {
    const proposal = exampleProposal({ field: 'name_en', live_value: 'Example name', proposed_value: 'Example name (source)' });
    const { user, acceptBody, onAccepted } = renderForm(proposal);
    const form = within(await dialog());
    await user.click(form.getByRole('button', { name: 'Accept' }));
    await waitFor(() => {
      expect(onAccepted).toHaveBeenCalled();
    });
    expect(acceptBody()).toEqual({ values: null, note: null });
  });

  it("create_entity of a project requires the scope note, then sends the person's values only", async () => {
    const proposal = exampleProposal({
      kind: 'create_entity',
      subject_id: null,
      field: null,
      live_value: null,
      proposed_value: null,
      payload: { fields: { name_uk: 'Приклад', official_urls: ['https://example.org/'] }, site_slug: 'example_site', candidates: [] },
    });
    const { user, fetchMock, acceptBody, onAccepted } = renderForm(proposal);
    const form = within(await dialog());
    expect(form.getByRole('textbox', { name: /Name \(UK\)/ })).toHaveValue('Приклад');

    await user.click(form.getByRole('button', { name: 'Accept' }));
    expect(await form.findByText(/Required/)).toBeInTheDocument();
    expect(callsTo(fetchMock, `/api/proposals/${proposal.id}/accept`)).toHaveLength(0);

    await user.type(form.getByRole('textbox', { name: /Scope note/ }), 'Example scope reason');
    await user.click(form.getByRole('switch', { name: /In paper scope/ }));
    await user.click(form.getByRole('button', { name: 'Accept' }));
    await waitFor(() => {
      expect(onAccepted).toHaveBeenCalled();
    });
    // Observed values stay with the proposal; the empty slug is generated by the server.
    expect(acceptBody()).toEqual({ values: { in_paper_scope: true, scope_note: 'Example scope reason' }, note: null });
  });

  it('create_event: the event fields that differ', async () => {
    const proposal = exampleProposal({
      kind: 'create_event',
      entity_type: 'event' as Proposal['entity_type'],
      field: null,
      live_value: null,
      proposed_value: null,
      payload: { event: { subject_id: 'prj_A', event_type: 'launch', date: '2001-02', date_basis: 'inferred', date_text: null, description_en: null } },
    });
    const { user, acceptBody, onAccepted } = renderForm(proposal);
    const form = within(await dialog());
    const date = form.getByRole('textbox', { name: /^Date$/ });
    await user.clear(date);
    await user.type(date, '2001-02-03');
    await user.click(form.getByRole('button', { name: 'Accept' }));
    await waitFor(() => {
      expect(onAccepted).toHaveBeenCalled();
    });
    expect(acceptBody()).toEqual({ values: { date: '2001-02-03' }, note: null });
  });

  it('possibly_discontinued: another status, sent as the only value', async () => {
    const proposal = exampleProposal({
      kind: 'possibly_discontinued',
      field: null,
      live_value: 'active',
      proposed_value: { status: 'discontinued' },
      payload: { reason: 'missing_from_listing' },
    });
    const { user, acceptBody, onAccepted } = renderForm(proposal);
    const form = within(await dialog());
    await user.click(form.getByRole('combobox', { name: /Status/ }));
    await user.click(await screen.findByRole('option', { name: /Example suspended/ }));
    await user.click(form.getByRole('button', { name: 'Accept' }));
    await waitFor(() => {
      expect(onAccepted).toHaveBeenCalled();
    });
    expect(acceptBody()).toEqual({ values: { status: 'suspended' }, note: null });
  });
});
